"""Writes cpp/engine/nfkc_units.h: the C++ engine's NFKC for what a model that knows English reads of a context (#41).

    py -3 tools/lm/next/make_nfkc_units.py

The training text is NFKC'd before its units are taken (tools/lm/next/text.py to_units: １．５ is one run, ⼀ is 一);
the engines normalize each character of a context the same way (engine/composer.py context_units uses unicodedata
character by character). C++ has no unicodedata: this lists every character whose NFKC differs where it or its NFKC
holds something the units read (a Chinese character, an ASCII letter or digit, - . _), with its NFKC.
tests/test_engine.py (NfkcUnitsTest) checks the header against this Python's unicodedata, every character: run this
again when it fails (another Unicode).
"""
import os
import sys
import unicodedata

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__)))))
OUT = os.path.join(ROOT, "cpp", "engine", "nfkc_units.h")


def read_by_units(ch):
    """A character context_units reads: a Chinese character (tools/lm/prepare.py RANGES), ASCII letter or digit, - . _"""
    o = ord(ch)
    return 0x3400 <= o <= 0x9FFF or 0xF900 <= o <= 0xFAFF or (ch.isascii() and (ch.isalnum() or ch in "-._"))


def table():
    """[(code point, its NFKC)] for every character whose NFKC differs, where it or its NFKC holds a character the units
    read."""
    out = []
    for cp in range(0x110000):
        if 0xD800 <= cp <= 0xDFFF:
            continue
        ch = chr(cp)
        m = unicodedata.normalize("NFKC", ch)
        # (either side read: U+FA6C is a Chinese character the units read, its NFKC U+242EE one they drop)
        if m != ch and (read_by_units(ch) or any(read_by_units(x) for x in m)):
            out.append((cp, m))
    return out


def header(rows):
    lines = ["// Generated by tools/lm/next/make_nfkc_units.py from Python %s's unicodedata (Unicode %s): do not edit."
             % (sys.version.split()[0], unicodedata.unidata_version),
             "// Every character whose NFKC differs where it or its NFKC holds what context_units reads (a Chinese "
             "character,",
             "// an ASCII letter or digit, - . _), with its NFKC, by code point (#41: the training text's NFKC, "
             "tools/lm/next/text.py).",
             "#pragma once",
             "",
             "namespace sz {",
             "",
             "struct NfkcUnit {",
             "    char32_t cp;",
             "    const char32_t* to;",
             "};",
             "",
             "inline constexpr NfkcUnit NFKC_UNITS[] = {"]
    for cp, m in rows:
        lines.append("    {0x%04X, U\"%s\"}," % (cp, "".join("\\U%08X" % ord(x) for x in m)))
    lines += ["};", "", "}  // namespace sz", ""]
    return "\n".join(lines)


def main():
    rows = table()
    with open(OUT, "w", encoding="ascii", newline="\n") as f:
        f.write(header(rows))
    print(f"{OUT}: {len(rows)} characters")


if __name__ == "__main__":
    main()
